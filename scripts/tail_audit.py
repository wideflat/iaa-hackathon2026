"""Tail and large-claim audit: where the cost sits, how heavy the tails are, how sensitive the cap and excess load are,
and what the single open 11.9M claim does to the bodily-injury excess load and the motor level.

  python scripts/tail_audit.py        # prints tables and writes docs/data/TAIL_AUDIT.md
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import genpareto

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from iaa import data, target  # noqa: E402
from iaa.config import LINES, REPO_ROOT  # noqa: E402


def md(df: pd.DataFrame, fmt: str = "{:,.3f}", index: bool = False) -> str:
    cols = ([""] if index else []) + [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for i, r in df.iterrows():
        cells = [("" if (isinstance(v, float) and np.isnan(v)) else (fmt.format(v) if isinstance(v, (float, np.floating)) else str(v))) for v in r]
        out.append("| " + " | ".join(([str(i)] if index else []) + cells) + " |")
    return "\n".join(out)


def excess_load(x: np.ndarray, q: float) -> tuple[float, float]:
    cap = float(np.quantile(x, q))
    capped = np.minimum(x, cap)
    return cap, float((x - capped).sum() / capped.sum())


def main() -> None:
    c = data.load_claims()
    c = c[(c.status != "repudiated") & (c.loss_date >= "2021-01-01")].copy()
    c["net"] = target.claim_net_cost(c)
    c = c[c.net > 0]
    c["year"] = c.loss_date.dt.year
    out = ["# Tail and large-claim audit (generated by scripts/tail_audit.py)\n", "Net cost = incurred - recoveries; repudiated excluded; accident years 2021-2024.\n"]

    # A) distribution and tail index per peril
    rows = []
    for (ln, pe), d in c.groupby(["line", "peril"]):
        x = np.sort(d.net.to_numpy())
        n = len(x)
        top1, top01 = x[-max(1, n // 100):].sum() / x.sum(), x[-max(1, n // 1000):].sum() / x.sum()
        k = max(20, n // 20)
        hill = 1.0 / np.mean(np.log(x[-k:] / x[-k - 1]))            # Hill tail index alpha on the top 5%
        u = np.quantile(x, 0.95)
        exc = x[x > u] - u
        xi, _, sigma = genpareto.fit(exc, floc=0)
        s_max = float(genpareto.sf(x[-1] - u, xi, loc=0, scale=sigma))   # P(excess >= largest observed | above u) under the fitted GPD
        rows.append(dict(line=ln, peril=pe, claims=n, mean=x.mean(), median=np.median(x), p99=np.quantile(x, .99), p999=np.quantile(x, .999), max=x[-1],
                         share_top1pct=top1, share_top01pct=top01, hill_alpha=hill, gpd_xi=xi, exp_claims_above_max=s_max * len(exc)))
    A = pd.DataFrame(rows)
    out += ["## 1. Where the cost sits and how heavy the tail is\n", md(A, "{:,.3f}"),
            "\nHill alpha is the tail index of the top 5% of claims (alpha < 2 means infinite variance); gpd_xi is the generalised-Pareto shape above the 95th percentile (xi > 0.5 means infinite variance); "
            "exp_claims_above_max = expected number of claims at least as large as the observed maximum among the exceedances, under the fitted GPD (a value far below 1 means the maximum is implausibly large for the rest of the tail).\n"]

    # B) cap sensitivity and the effect of the single largest claim, per peril
    rows = []
    for (ln, pe), d in c.groupby(["line", "peril"]):
        x = d.net.to_numpy()
        r = dict(line=ln, peril=pe)
        for q in (0.99, 0.995, 0.999, 0.9999):
            cap, el = excess_load(x, q)
            r[f"cap@{q}"] = cap
            r[f"xs@{q}"] = el
        xs = np.sort(x)[:-1]                                           # drop the single largest claim
        r["xs@0.999_no_max"] = excess_load(xs, 0.999)[1]
        rows.append(r)
    B = pd.DataFrame(rows)
    out += ["## 2. Cap and excess-load sensitivity\n", "Excess load = sum(cost above the cap) / sum(capped cost). `no_max` drops the single largest claim of the peril.\n", md(B, "{:,.4f}"), ""]

    # C) excess load stability by accident year
    rows = []
    for (ln, pe), d in c.groupby(["line", "peril"]):
        cap = float(np.quantile(d.net, 0.999))
        r = dict(line=ln, peril=pe, cap=cap)
        for y, g in d.groupby("year"):
            r[str(y)] = float((g.net - np.minimum(g.net, cap)).sum() / np.minimum(g.net, cap).sum())
        rows.append(r)
    C = pd.DataFrame(rows)
    out += ["## 3. Excess load by accident year at the 99.9th-percentile cap (all years' cap)\n", md(C, "{:,.4f}"), ""]

    # D) the largest claims and their status
    big = c.sort_values("net", ascending=False).head(12)[["claim_id", "line", "peril", "loss_date", "report_date", "status", "paid_to_date", "incurred_to_date", "net"]]
    big["paid/incurred"] = big.paid_to_date / big.incurred_to_date
    big["loss_date"], big["report_date"] = big.loss_date.dt.date.astype(str), big.report_date.dt.date.astype(str)
    out += ["## 4. The 12 largest claims\n", md(big.drop(columns=["claim_id"]), "{:,.2f}"), ""]
    thr = c.groupby(["line", "peril"]).net.transform(lambda s: s.quantile(0.999))
    top = c[c.net >= thr]
    st = top.groupby(["line", "peril"]).apply(lambda d: pd.Series({"claims_above_p99.9": len(d), "open_share": (d.status == "open").mean(), "paid_to_incurred": d.paid_to_date.sum() / d.incurred_to_date.sum()}), include_groups=False)
    out += ["Claims above their peril's 99.9th percentile: status and payment progress.\n", md(st.reset_index(), "{:,.3f}"), ""]

    # E) effect of the largest bodily-injury claim on the motor level
    bi = c[(c.line == "motor") & (c.peril == "bodily_injury")].net.to_numpy()
    motor = c[c.line == "motor"]
    cap, xs_all = excess_load(bi, 0.999)
    xs_no = excess_load(np.sort(bi)[:-1], 0.999)[1]
    capped_motor = sum(np.minimum(g.net, g.net.quantile(0.999)).sum() for _, g in motor.groupby("peril"))
    capped_bi = np.minimum(bi, cap).sum()
    share_bi = capped_bi / capped_motor
    effect = share_bi * ((1 + xs_all) / (1 + xs_no) - 1)
    out += ["## 5. What the single largest bodily-injury claim does to the motor level\n",
            f"- Bodily-injury excess load at the 99.9th-percentile cap: {xs_all:.4f} with the largest claim, {xs_no:.4f} without it.",
            f"- Bodily injury is {100 * share_bi:.1f}% of capped motor cost, so that claim raises the model's motor level by about {100 * effect:.2f}% (excess-load channel only).\n"]

    # F) row-level concentration
    rows = []
    for ln in LINES:
        r, _ = target.build_row_target(data.load_policies(ln), data.load_claims(), ln)
        y = np.sort(r.y.to_numpy())
        rows.append(dict(line=ln, rows=len(y), share_top01pct_rows=y[-max(1, len(y) // 1000):].sum() / y.sum(), share_top1pct_rows=y[-len(y) // 100:].sum() / y.sum(),
                         rows_over_250k=int((y >= 250_000).sum()), share_cost_rows_over_250k=y[y >= 250_000].sum() / y.sum()))
    out += ["## 6. Concentration at policy-row level (training years)\n", md(pd.DataFrame(rows), "{:,.4f}"), ""]
    (REPO_ROOT / "docs" / "data" / "TAIL_AUDIT.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
