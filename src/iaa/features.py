"""Feature construction. Every feature must be knowable when the 2025 policy is priced.

Leak guards (each has a test):
  * `renewal_decision` exists only in training files: never a feature.
  * Claim-history features for a row in year Y use only claims with loss_date AND report_date
    on or before 31 Dec of Y-1, i.e. exactly what we know when predicting 2025 from the
    2024 valuation. Validation folds therefore see the same information structure as the test.
  * Static joins (customer, address) are time-invariant in the data; weather is joined on the
    row's own year (the file also contains the 2025 weather needed for the test rows).
"""
import numpy as np
import pandas as pd

from . import data, target
from .config import LINES

ID_COLS = ["row_id", "policy_id", "customer_id", "address_id"]
DATE_COLS = ["period_start", "period_end", "date_of_birth"]
TARGET_COLS = ["y", "y_true", "n_claims", "pred"]
LABEL_ONLY_COLS = ["renewal_decision"]  # training files only
# Generated by the outcome in training rows (claims cause contacts) but only baseline in 2025 rows:
# train corr with claim count 0.55 (motor); 2025 mean 0.40 vs 0.67 in training. Using it gives CV D2 ~0.55
# and a collapse on the test set. See docs/DATA_QUALITY.md.
OUTCOME_LEAK_COLS = ["customer_service_contacts"]
EXPOSURE_COLS = ["exposure", "exposure_calc"]  # model uses exposure_calc as the offset
BOOKKEEPING_COLS = ["year", "line", "split"]

# Fields that look like noise or marketing artefacts. Excluded by default; ablated in experiments.
NOISE_COLS = [
    "surname", "email_domain", "vehicle_colour", "branch_id", "campaign_code",
    "document_preference", "marketing_consent", "marketing_segment", "previous_insurer",
]


def add_claim_history(rows: pd.DataFrame, claims_line: pd.DataFrame) -> pd.DataFrame:
    """Prior-claims features per policy, as known at the end of the previous calendar year."""
    c = claims_line[claims_line["status"] != "repudiated"].copy()
    c["net_cost"] = target.claim_net_cost(c)
    c["loss_year"] = c["loss_date"].dt.year
    pieces = []
    for year in sorted(rows["year"].unique()):
        cutoff = pd.Timestamp(year - 1, 12, 31)
        known = c[(c["loss_date"] <= cutoff) & (c["report_date"] <= cutoff)]
        g = known.groupby("policy_id")
        feat = pd.DataFrame({
            "hist_n_claims": g.size(),
            "hist_cost": g["net_cost"].sum(),
            "hist_n_last_year": known[known["loss_year"] == year - 1].groupby("policy_id").size(),
        }).fillna(0.0)
        r = rows.loc[rows["year"] == year, ["row_id", "policy_id"]].merge(
            feat, left_on="policy_id", right_index=True, how="left")
        pieces.append(r.drop(columns="policy_id").fillna({"hist_n_claims": 0, "hist_cost": 0.0, "hist_n_last_year": 0}))
    return rows.merge(pd.concat(pieces), on="row_id", how="left")


def build_line_frame(line: str, data_dir=None, customers=None, addresses=None, weather=None, claims=None) -> pd.DataFrame:
    """Train + test rows of one line in one frame, with target (train only) and all joins."""
    claims = data.load_claims(data_dir) if claims is None else claims
    customers = data.load_customers(data_dir) if customers is None else customers
    addresses = data.load_addresses(data_dir) if addresses is None else addresses
    weather = data.load_weather(data_dir) if weather is None else weather

    train, _ = target.build_row_target(data.load_policies(line, data_dir), claims, line)
    train["split"] = "train"
    test = data.load_test(line, data_dir)
    test["exposure_calc"] = target.recompute_exposure(test)
    test["split"] = "test"
    df = pd.concat([train, test], ignore_index=True)
    df["line"] = line

    df = df.merge(customers, on="customer_id", how="left").merge(addresses, on="address_id", how="left")
    df = df.merge(weather, on=["address_id", "year"], how="left")
    df["customer_age"] = (df["period_start"] - df["date_of_birth"]).dt.days / 365.25
    df = add_claim_history(df, claims[claims["line"] == line])
    return df


def feature_columns(df: pd.DataFrame, drop_noise: bool = True, extra_drop=()) -> list:
    """Columns usable as model inputs after removing ids, dates, targets and leakage."""
    drop = set(ID_COLS + DATE_COLS + TARGET_COLS + LABEL_ONLY_COLS + OUTCOME_LEAK_COLS + EXPOSURE_COLS + BOOKKEEPING_COLS) | set(extra_drop)
    if drop_noise:
        drop |= set(NOISE_COLS)
    return [c for c in df.columns if c not in drop and not df[c].isna().all()]
