"""Build annual loss (count and dollar) triangles, link ratios, LDFs and developed ultimates by line.

  python scripts/ldf.py            # prints tables and writes docs/data/LDF_TABLES.md
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from iaa import data, development as dev, target  # noqa: E402
from iaa.config import REPO_ROOT  # noqa: E402

YEARS = (2021, 2022, 2023, 2024)


def md(df: pd.DataFrame, fmt="{:,.3f}", index=True) -> str:
    cols = ([""] if index else []) + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for i, r in df.iterrows():
        cells = [("" if (isinstance(v, float) and np.isnan(v)) else (fmt.format(v) if isinstance(v, (int, float, np.floating)) else str(v))) for v in r]
        lines.append("| " + " | ".join(([str(i)] if index else []) + cells) + " |")
    return "\n".join(lines)


def main() -> None:
    c = data.load_claims()
    c = c[(c["status"] != "repudiated") & (c["loss_date"] >= "2021-01-01")].copy()
    c["net"] = target.claim_net_cost(c)
    groups = {
        "Motor (all perils)": c[c.line == "motor"],
        "Motor bodily injury": c[(c.line == "motor") & (c.peril == "bodily_injury")],
        "Motor bodily injury (cost capped at 250k per claim)": c[(c.line == "motor") & (c.peril == "bodily_injury")].assign(net=lambda d: d["net"].clip(upper=250_000)),
        "Motor excl. bodily injury": c[(c.line == "motor") & (c.peril != "bodily_injury")],
        "Buildings": c[c.line == "buildings"],
        "Contents": c[c.line == "contents"],
    }
    out = ["# Loss triangles and LDFs (generated by scripts/ldf.py)\n",
           "As-if reported triangles at annual valuations (31 Dec). Each reported claim carries its *current* amount, so",
           "only reporting emergence (pure IBNR) is captured; development of case estimates (IBNER) cannot be measured",
           "from one snapshot. Ages are months since 1 Jan of the accident year. Selected = volume-weighted, all accident years.\n"]
    summary = []
    for name, d in groups.items():
        out.append(f"\n## {name}\n")
        for label, val, fmt in (("Claim counts", None, "{:,.0f}"), ("Net cost (incurred - recoveries)", "net", "{:,.0f}")):
            tri = dev.annual_triangle(d, val, YEARS)
            ind = dev.individual_links(tri)
            avg = dev.average_links(tri, latest=2)
            sel = pd.Series(dev.link_ratios(tri.set_axis(range(tri.shape[1]), axis=1)), index=ind.columns)
            tail = dev.tail_exp_decay(sel.values)
            cdf = pd.Series(dev.factors_to_ultimate(sel.values, tail), index=tri.columns)
            asval = pd.Series({y: tri.loc[y].dropna().iloc[-1] for y in YEARS})
            age_now = pd.Series({y: 12 * (2024 - y + 1) for y in YEARS})
            ult = pd.Series({y: asval[y] * cdf[age_now[y]] for y in YEARS})
            out += [f"### {label}: cumulative triangle\n", md(tri, fmt), "\n", "Age-to-age ratios\n", md(pd.concat([ind, avg])), "\n",
                    f"Selected link ratios: {', '.join(f'{k}: {v:.3f}' for k, v in sel.items())}; tail beyond 48m (exp. decay, extrapolated): {tail:.4f}\n",
                    "Cumulative development factor to ultimate: " + ", ".join(f"{a}m: {v:.3f}" for a, v in cdf.items()) + "\n",
                    md(pd.DataFrame({"as valued": asval, "age (m)": age_now, "CDF to ult": [cdf[age_now[y]] for y in YEARS], "ultimate": ult, "uplift %": 100 * (ult / asval - 1)}), "{:,.2f}"), "\n"]
            summary.append(dict(group=name, basis=label.split(" (")[0], **{f"AY{y} uplift %": round(100 * (ult[y] / asval[y] - 1), 1) for y in YEARS}, **{f"CDF{a}": round(v, 3) for a, v in cdf.items()}, tail=round(tail, 4)))
    s = pd.DataFrame(summary)
    out.insert(4, "## Summary\n\n" + md(s, "{:,.3f}", index=False) + "\n")
    (REPO_ROOT / "docs" / "data" / "LDF_TABLES.md").write_text("\n".join(out))
    pd.set_option("display.width", 250); pd.set_option("display.max_columns", 30)
    print(s.to_string(index=False))


if __name__ == "__main__":
    main()
