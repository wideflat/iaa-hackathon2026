"""Where is the best blend wrong? Calibration (actual / predicted cost) by bins of every feature, with a cluster-robust z-score, on the out-of-fold predictions.

  python scripts/residual_scan.py            # blend = target GBM + mean(TabM, TabM-PLE), per-line NN weights 0.7 / 0.4 / 0.3 (v5)
Output: docs/data/RESIDUAL_SCAN.md (largest |z| first) and the by-decile calibration table. A bin is only listed when it holds at least 1,000 rows and 2% of the line's predicted cost.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from iaa import cache  # noqa: E402
from iaa.config import ARTIFACTS_DIR, LINES, REPO_ROOT  # noqa: E402
from iaa.features import feature_columns  # noqa: E402

W = {"motor": 0.7, "buildings": 0.4, "contents": 0.3}


def load(n):
    return pd.read_parquet(ARTIFACTS_DIR / f"oof_{n}.parquet")


def _md(df: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join(f"{v:.3f}" if isinstance(v, (float, np.floating)) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main() -> None:
    g = load("fs_gbm_target")[["row_id", "customer_id", "line", "y", "fold", "pred"]].rename(columns={"pred": "g"})
    for n, k in (("fs_nn_tabm4", "t"), ("fs_nn_tabm4_ple", "p")):
        g = g.merge(load(n)[["row_id", "fold", "pred"]].rename(columns={"pred": k}), on=["row_id", "fold"])
    g["nn"] = 0.5 * g["t"] + 0.5 * g["p"]
    w = g["line"].map(W)
    g["pred"] = (1 - w) * g["g"] + w * g["nn"]
    frames = cache.load_frames()
    rows, deciles = [], []
    for line in LINES:
        d = g[g["line"] == line]
        f = frames[line].set_index("row_id")
        cols = feature_columns(frames[line][frames[line]["split"] == "train"], True, ())
        d = d.join(f[cols], on="row_id")
        tot_pred = d["pred"].sum()
        d["res"] = d["y"] - d["pred"]
        q = pd.qcut(d["pred"].rank(method="first"), 10, labels=False)
        dec = d.groupby(q).agg(pred=("pred", "sum"), y=("y", "sum"))
        dec["ratio"] = dec["y"] / dec["pred"]
        deciles.append((line, dec))
        cust = d["customer_id"]
        for c in cols:
            s = d[c]
            if pd.api.types.is_bool_dtype(s) or s.dtype == object or str(s.dtype) in ("str", "string", "category") or s.nunique() <= 12:
                key = s.astype(object).where(s.notna(), "missing").astype(str)
            else:
                key = pd.qcut(s.rank(method="first"), 10, labels=False).astype(str)
            for lv, idx in key.groupby(key).groups.items():
                x = d.loc[idx]
                if len(x) < 1000 or x["pred"].sum() < 0.02 * tot_pred:
                    continue
                cs = x.groupby(cust.loc[idx])["res"].sum()
                z = x["res"].sum() / np.sqrt((cs ** 2).sum())
                rows.append((line, c, lv, len(x), x["y"].sum() / x["pred"].sum(), z, x["pred"].sum() / tot_pred))
    res = pd.DataFrame(rows, columns=["line", "feature", "level_or_decile", "rows", "actual_over_pred", "z", "share_of_pred"])
    res = res.reindex(res["z"].abs().sort_values(ascending=False).index)
    out = REPO_ROOT / "docs" / "data" / "RESIDUAL_SCAN.md"
    with open(out, "w") as fh:
        fh.write("# Residual scan of the v5 blend (out-of-fold, folds A and B pooled)\n\nGenerated by `scripts/residual_scan.py`. actual_over_pred = sum of cost / sum of predictions in the bin; z = cluster-robust (by customer) z-score of the residual sum.\n\n")
        fh.write("## Calibration by prediction decile\n\n")
        for line, dec in deciles:
            fh.write(f"**{line}** (actual / predicted by decile 0-9): " + ", ".join(f"{v:.2f}" for v in dec["ratio"]) + "\n\n")
        fh.write("## Largest deviations by feature bin (|z| first)\n\n" + _md(res.head(40)) + "\n")
    print(open(out).read()[:6000])


if __name__ == "__main__":
    main()
